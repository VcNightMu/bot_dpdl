"""#help 帮助信息格式化模块"""
from __future__ import annotations


def format_help() -> str:
    """格式化帮助信息"""
    return """📋 少人WIKI 低配低练记录查询Bot

#查 <关卡> <流派> — 按关卡查最佳记录
#人数 <关卡> [流派...] — 查关卡各流派人数统计
#干员记录 <干员> <流派> — 查干员在某流派的记录数
#干员记录 <干员A>+<干员B> <流派> — 查多干员在流派同时上场记录数
#未通关 <活动名> <流派> — 查未通关关卡
#待压人 <活动名> <流派> [天数] — 查待压人记录（默认365天）
#高难 <活动名> <流派> [人数] — 查该流派人数达标的关卡（默认 10 人）
#流派 — 查看所有流派
#help — 显示本帮助

💡 活动名支持缩写查询：
  主线章节：#未通关 第五章 四星队 或 #未通关 5 四星队
  活动缩写：#未通关 SV 四星队
  ⚠️ 缩写对应多个活动时会提示选择

💡 剿灭作战（不区分长期/轮换委托）：
  活动级：#未通关 剿灭 四星队 / #待压人 剿灭 四星队
  关卡级：#查 多索雷斯换水口 四星队（直接输关卡名）

💡 干员组合查询（用 + 连接，查同时上场的记录）：
  #干员记录 羽毛笔+银灰 无精英满级
  #干员记录 羽毛笔+银灰+史尔特尔 无精英满级（任意多个，最多13个）

💡 #干员记录 统计说明：
  四行：总记录 / 有效记录 / 合约记录 / 旧纪录
  总记录 = 有效记录 + 合约记录 + 旧纪录
  合约记录 = 危机合约（含Re）的有效记录，因合约非常驻单独统计
  合约旧纪录计入旧纪录，不计入合约记录

💡 #高难 说明：
  「高难」= 该关在该流派下，最少人记录也需达到指定人数
  人数可省略（默认 10），也可自定：不同流派人数基数不同，
  如「精一1级」很少有 10 人以上的图，可传更小的值
  取值 1–13，例如：#高难 惊霆无声 精一1级 6

示例：#查 H11-1 四星队
示例：#人数 M8-8 四星队 精一满级
示例：#干员记录 羽毛笔 无精英满级
示例：#干员记录 羽毛笔+银灰 无精英满级
示例：#高难 巴别塔 四星队"""
